SET NAMES utf8mb4;

-- 网络请求观测（通用能力，非某项目专用）：慢请求 / 失败请求明细 + 聚合问题表。
-- 明细不去重靠 dedup_hash（客户端重试幂等）；聚合指纹由服务端归一化 path 后计算。
CREATE TABLE IF NOT EXISTS logan_http (
  id BIGINT NOT NULL AUTO_INCREMENT,
  app_id VARCHAR(128) NOT NULL COMMENT '应用标识（端粒度）',
  device_id VARCHAR(128) NOT NULL,
  platform TINYINT NOT NULL DEFAULT 0 COMMENT '1 android 2 ios 3 harmony，0=未知',
  kind VARCHAR(16) NOT NULL DEFAULT 'native' COMMENT 'native/h5',
  method VARCHAR(16) NOT NULL DEFAULT 'GET',
  url TEXT COMMENT '完整 URL（query 已脱敏）',
  host VARCHAR(255) DEFAULT NULL,
  path VARCHAR(512) DEFAULT NULL COMMENT '归一化后的路径（数字/UUID 段折叠）',
  status INT NOT NULL DEFAULT 0 COMMENT 'HTTP 状态码，0=没拿到响应',
  err_kind VARCHAR(24) DEFAULT NULL COMMENT 'timeout/connect/ssl/parse/cancel/other，成功为 NULL',
  err_msg VARCHAR(1024) DEFAULT NULL,
  duration_ms BIGINT NOT NULL DEFAULT 0,
  connect_ms BIGINT DEFAULT NULL,
  dns_ms BIGINT DEFAULT NULL,
  ttfb_ms BIGINT DEFAULT NULL COMMENT '首字节耗时',
  req_bytes BIGINT DEFAULT NULL,
  resp_bytes BIGINT DEFAULT NULL,
  slow TINYINT NOT NULL DEFAULT 0 COMMENT '是否超慢阈值（阈值由客户端上报时判定）',
  page_url VARCHAR(1024) DEFAULT NULL COMMENT 'h5 来源页面',
  trace_id VARCHAR(64) DEFAULT NULL COMMENT '同一次请求在页面/原生两侧的关联 id',
  app_version VARCHAR(64) DEFAULT NULL,
  build_version VARCHAR(64) DEFAULT NULL,
  os VARCHAR(32) DEFAULT NULL,
  os_version VARCHAR(64) DEFAULT NULL,
  brand VARCHAR(64) DEFAULT NULL,
  model VARCHAR(128) DEFAULT NULL,
  network_type VARCHAR(32) DEFAULT NULL,
  extra TEXT COMMENT '扩展 JSON（不解析，展示用）',
  occurred_at BIGINT NOT NULL COMMENT '请求开始时间（客户端时钟，毫秒）',
  fingerprint VARCHAR(128) NOT NULL COMMENT '聚合指纹',
  dedup_hash CHAR(40) NOT NULL COMMENT 'SHA-1(appId|deviceId|traceId|occurredAt|url) 幂等去重',
  add_time BIGINT NOT NULL,
  update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_dedup (dedup_hash),
  KEY idx_app_time (app_id, occurred_at),
  KEY idx_app_dev_time (app_id, device_id, occurred_at),
  KEY idx_fp (app_id, fingerprint),
  KEY idx_slow (app_id, slow, occurred_at),
  KEY idx_err (app_id, err_kind, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='网络请求观测明细（慢/失败）';

CREATE TABLE IF NOT EXISTS logan_http_issue (
  id BIGINT NOT NULL AUTO_INCREMENT,
  app_id VARCHAR(128) NOT NULL,
  fingerprint VARCHAR(128) NOT NULL,
  kind VARCHAR(16) NOT NULL DEFAULT 'native',
  method VARCHAR(16) DEFAULT NULL,
  host VARCHAR(255) DEFAULT NULL,
  path VARCHAR(512) DEFAULT NULL,
  status INT NOT NULL DEFAULT 0,
  err_kind VARCHAR(24) DEFAULT NULL,
  title VARCHAR(512) NOT NULL COMMENT '展示标题：METHOD host/path STATUS',
  sample_url TEXT COMMENT '最近一次样本 URL',
  sample_device_id VARCHAR(128) DEFAULT NULL,
  sample_trace_id VARCHAR(64) DEFAULT NULL,
  error_count INT NOT NULL DEFAULT 0 COMMENT '失败次数（4xx/5xx 或传输错误）',
  slow_count INT NOT NULL DEFAULT 0 COMMENT '慢请求次数',
  total_count INT NOT NULL DEFAULT 0 COMMENT '该指纹样本总数（受采样影响）',
  avg_ms BIGINT NOT NULL DEFAULT 0,
  max_ms BIGINT NOT NULL DEFAULT 0,
  last_err_msg VARCHAR(1024) DEFAULT NULL,
  affected_devices VARCHAR(512) DEFAULT NULL COMMENT '逗号分隔 deviceId（上限 50）',
  status_flag TINYINT NOT NULL DEFAULT 0 COMMENT '0 未处理 1 处理中 2 已修复',
  last_fix_note TEXT COMMENT '历史修复全文（同指纹复现时带出）',
  reopen_count INT NOT NULL DEFAULT 0,
  llm_summary TEXT COMMENT 'AI 定性摘要（可选）',
  llm_severity VARCHAR(16) DEFAULT NULL,
  first_seen BIGINT NOT NULL,
  last_seen BIGINT NOT NULL,
  add_time BIGINT NOT NULL,
  update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_app_fp (app_id, fingerprint),
  KEY idx_app_last (app_id, last_seen),
  KEY idx_app_status (app_id, status_flag, last_seen)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='网络请求聚合问题（慢请求/异常）';

