CREATE TABLE IF NOT EXISTS logan_crash (
  id BIGINT NOT NULL AUTO_INCREMENT,
  app_id VARCHAR(64) NOT NULL,
  platform INT NOT NULL DEFAULT 1,
  kind VARCHAR(16) NOT NULL,
  fingerprint VARCHAR(64) NOT NULL,
  device_id VARCHAR(128) DEFAULT NULL,
  union_id VARCHAR(128) DEFAULT NULL,
  user_id VARCHAR(128) DEFAULT NULL,
  app_version VARCHAR(32) DEFAULT NULL,
  build_version VARCHAR(32) DEFAULT NULL,
  brand VARCHAR(64) DEFAULT NULL,
  model VARCHAR(128) DEFAULT NULL,
  manufacturer VARCHAR(64) DEFAULT NULL,
  sdk_int INT DEFAULT NULL,
  release_ver VARCHAR(32) DEFAULT NULL,
  abi VARCHAR(32) DEFAULT NULL,
  signal_info VARCHAR(128) DEFAULT NULL,
  top_frames TEXT,
  deferred TINYINT NOT NULL DEFAULT 0,
  crash_time BIGINT NOT NULL,
  add_time BIGINT NOT NULL,
  content MEDIUMTEXT,
  content_hash CHAR(40) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_content_hash (content_hash),
  KEY idx_fp (app_id, fingerprint),
  KEY idx_device (device_id),
  KEY idx_time (crash_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS logan_crash_issue (
  id BIGINT NOT NULL AUTO_INCREMENT,
  app_id VARCHAR(64) NOT NULL,
  platform INT NOT NULL DEFAULT 1,
  kind VARCHAR(16) NOT NULL,
  fingerprint VARCHAR(64) NOT NULL,
  sample_content MEDIUMTEXT,
  top_frames TEXT,
  signal_info VARCHAR(128) DEFAULT NULL,
  first_crash_time BIGINT DEFAULT NULL,
  last_crash_time BIGINT DEFAULT NULL,
  crash_count INT NOT NULL DEFAULT 0,
  affected_devices TEXT,
  llm_summary TEXT,
  llm_severity VARCHAR(32) DEFAULT NULL,
  status INT NOT NULL DEFAULT 0,
  add_time BIGINT DEFAULT NULL,
  update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_fp (app_id, fingerprint),
  KEY idx_last (last_crash_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
